@router.get("/{user_id}", response_model=AdminUserOut)
async def get_user(user_id: int, db: Session = Depends(get_db)):
    return to_out(_get_user(db, user_id))


@router.patch("/{user_id}", response_model=AdminUserOut)
async def update_user(
    user_id: int,
    data: AdminUserUpdate,
    admin: User = Depends(require_admin),
    db: Session = Depends(get_db),
):
    user = _get_user(db, user_id)
    changes = []

    if data.email is not None and data.email.lower() != user.email.lower():
        if db.query(User).filter(func.lower(User.email) == data.email.lower(), User.id != user.id).first():
            raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Email already in use")
        user.email = data.email
        user.is_verified = True
        changes.append("email")

    if data.full_name is not None and data.full_name != (user.full_name or ""):
        user.full_name = data.full_name or None
        changes.append("name")

    role_event = None
    if data.role is not None and data.role != user.role:
        _refuse_self(admin, user, "change the role of")
        if user.role == UserRole.ADMIN:
            _refuse_last_admin(db, user, "demoted")
        role_event = f"{user.role.value} -> {data.role.value}"
        user.role = data.role
        # Tokens carry the role for display only, but a demotion should take effect
        # in every open session right away
        user.token_version += 1

    status_event = None
    if data.is_active is not None and data.is_active != user.is_active:
        if not data.is_active:
            _refuse_self(admin, user, "deactivate")
            _refuse_last_admin(db, user, "deactivated")
            user.token_version += 1
            status_event = audit_service.USER_DEACTIVATED
        else:
            user.failed_login_attempts = 0
            user.locked_until = None
            status_event = audit_service.USER_ACTIVATED
        user.is_active = data.is_active

    if changes:
        audit_service.record(
            db, admin, audit_service.USER_UPDATED, user, detail=", ".join(changes), commit=False
        )
    if role_event:
        audit_service.record(
            db, admin, audit_service.USER_ROLE_CHANGED, user, detail=role_event, commit=False
        )
    if status_event:
        audit_service.record(db, admin, status_event, user, commit=False)

    user.updated_at = datetime.now(timezone.utc)
    db.commit()
    db.refresh(user)
    return to_out(user)


@router.post("/{user_id}/unlock", response_model=AdminUserOut)
async def unlock_user(
    user_id: int, admin: User = Depends(require_admin), db: Session = Depends(get_db)
):
    user = _get_user(db, user_id)
    user.failed_login_attempts = 0
    user.locked_until = None
    audit_service.record(db, admin, audit_service.USER_UNLOCKED, user, commit=False)
    db.commit()
    db.refresh(user)
    return to_out(user)


@router.post("/{user_id}/reset-password", response_model=AdminUserWithPassword)
async def reset_password(
    user_id: int,
    data: AdminPasswordReset,
    admin: User = Depends(require_admin),
    db: Session = Depends(get_db),
):
    """
    Set a new temporary password (generated unless one is given). The old password
    and all running sessions stop working; the user must choose a new password.
    """
    user = _get_user(db, user_id)
    _refuse_self(admin, user, "reset the password of")
    temporary = _set_temporary_password(user, data.password)
    audit_service.record(db, admin, audit_service.USER_PASSWORD_RESET, user, commit=False)
    db.commit()
    db.refresh(user)
    return AdminUserWithPassword(user=to_out(user), temporary_password=temporary)


@router.post("/{user_id}/revoke-sessions", response_model=AdminUserOut)
async def revoke_sessions(
    user_id: int, admin: User = Depends(require_admin), db: Session = Depends(get_db)
):
    """Sign the user out everywhere (all issued access tokens stop working)."""
    user = _get_user(db, user_id)
    user.token_version += 1
    audit_service.record(db, admin, audit_service.USER_SESSIONS_REVOKED, user, commit=False)
    db.commit()
    db.refresh(user)
    return to_out(user)


@router.delete("/{user_id}")
async def delete_user(
    user_id: int, admin: User = Depends(require_admin), db: Session = Depends(get_db)
):
    user = _get_user(db, user_id)
    _refuse_self(admin, user, "delete")
    _refuse_last_admin(db, user, "deleted")
    username = user.username
    audit_service.record(db, admin, audit_service.USER_DELETED, user, commit=False)
    user_service.delete_user_and_data(db, user)
    db.commit()
    return {"message": f"User {username} deleted"}
