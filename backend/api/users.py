"""
User management for administrators.

Everything here needs the admin role (router-wide dependency). Rules that keep
the system usable and safe:

- An admin cannot lock themselves out: no deactivating, deleting or demoting
  your own account here (use the profile page for your own account).
- The last active administrator can never be demoted, deactivated or deleted,
  so the instance cannot end up without an admin.
- Passwords chosen or generated by an admin are temporary: the user must set
  their own at the first sign-in, and all running sessions of the account end.
- Every change is written to the audit log (never with passwords or tokens).
"""

import logging
from datetime import datetime, timezone
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy import func, or_
from sqlalchemy.orm import Session

from ..database import get_db
from ..dependencies.auth import require_admin
from ..models import AuditEvent, User, UserRole
from ..schemas.auth import (
    AdminPasswordReset,
    AdminUserCreate,
    AdminUserList,
    AdminUserOut,
    AdminUserUpdate,
    AdminUserWithPassword,
    AuditEventList,
    RegistrationSetting,
)
from ..security import passwords
from ..services import audit_service, settings_service, user_service

logger = logging.getLogger(__name__)

router = APIRouter(dependencies=[Depends(require_admin)])


# --- helpers ----------------------------------------------------------------


def _as_utc(value: Optional[datetime]) -> Optional[datetime]:
    if value is not None and value.tzinfo is None:
        return value.replace(tzinfo=timezone.utc)
    return value


def to_out(user: User) -> AdminUserOut:
    locked = _as_utc(user.locked_until)
    return AdminUserOut(
        id=user.id,
        username=user.username,
        email=user.email,
        full_name=user.full_name,
        role=user.role,
        is_active=user.is_active,
        is_verified=user.is_verified,
        is_locked=bool(locked and locked > datetime.now(timezone.utc)),
        totp_enabled=user.totp_enabled,
        must_change_password=user.must_change_password,
        created_at=user.created_at,
        last_login_at=user.last_login_at,
        failed_login_attempts=user.failed_login_attempts,
    )


def _get_user(db: Session, user_id: int) -> User:
    user = db.query(User).filter(User.id == user_id).first()
    if not user:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="User not found")
    return user


def _other_active_admins(db: Session, exclude_id: int) -> int:
    return (
        db.query(User)
        .filter(User.role == UserRole.ADMIN, User.is_active == True, User.id != exclude_id)
        .count()
    )


def _refuse_self(actor: User, target: User, what: str) -> None:
    if actor.id == target.id:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"You cannot {what} your own account here.",
        )


def _refuse_last_admin(db: Session, target: User, what: str) -> None:
    if (
        target.role == UserRole.ADMIN
        and target.is_active
        and _other_active_admins(db, target.id) == 0
    ):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"This is the last active administrator and cannot be {what}.",
        )


def _check_password(password: str) -> str:
    try:
        return passwords.validate_strength(password)
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail=str(exc))


def _set_temporary_password(user: User, password: Optional[str]) -> Optional[str]:
    """Set an admin-chosen password. Returns the generated one (shown once), else None."""
    generated = None
    if password is None:
        password = generated = passwords.generate_temporary_password()
    else:
        _check_password(password)
    user.hashed_password = passwords.hash_password(password)
    user.must_change_password = True
    user.token_version += 1
    user.failed_login_attempts = 0
    user.locked_until = None
    return generated


