@router.get("", response_model=AdminUserList)
async def list_users(
    q: Optional[str] = Query(None, max_length=100, description="Search user name, e-mail, name"),
    role: Optional[UserRole] = None,
    status_filter: Optional[str] = Query(None, alias="status", pattern="^(active|inactive|locked)$"),
    page: int = Query(1, ge=1),
    page_size: int = Query(25, ge=1, le=100),
    db: Session = Depends(get_db),
):
    query = db.query(User)
    if q:
        like = f"%{q.strip().lower()}%"
        query = query.filter(
            or_(
                func.lower(User.username).like(like),
                func.lower(User.email).like(like),
                func.lower(func.coalesce(User.full_name, "")).like(like),
            )
        )
    if role:
        query = query.filter(User.role == role)
    if status_filter == "active":
        query = query.filter(User.is_active == True)
    elif status_filter == "inactive":
        query = query.filter(User.is_active == False)
    elif status_filter == "locked":
        query = query.filter(User.locked_until != None, User.locked_until > datetime.now(timezone.utc))

    total = query.count()
    rows = (
        query.order_by(User.username)
        .offset((page - 1) * page_size)
        .limit(page_size)
        .all()
    )
    return AdminUserList(
        total=total, page=page, page_size=page_size, items=[to_out(u) for u in rows]
    )


@router.post("", response_model=AdminUserWithPassword, status_code=status.HTTP_201_CREATED)
async def create_user(
    data: AdminUserCreate,
    admin: User = Depends(require_admin),
    db: Session = Depends(get_db),
):
    """Create an account. The user has to choose their own password at the first sign-in."""
    if db.query(User).filter(func.lower(User.email) == data.email.lower()).first():
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Email already registered")
    if db.query(User).filter(User.username == data.username).first():
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Username already taken")

    user = User(
        username=data.username,
        email=data.email,
        full_name=data.full_name,
        role=data.role,
        is_active=True,
        is_verified=True,  # created by an admin: no e-mail check needed
        token_version=0,
        hashed_password="!",  # replaced right below
    )
    temporary = _set_temporary_password(user, data.password)
    db.add(user)
    db.flush()
    audit_service.record(
        db, admin, audit_service.USER_CREATED, user, detail=f"role={user.role.value}", commit=False
    )
    db.commit()
    db.refresh(user)
    return AdminUserWithPassword(user=to_out(user), temporary_password=temporary)


@router.get("/settings/registration", response_model=RegistrationSetting)
async def get_registration(db: Session = Depends(get_db)):
    return RegistrationSetting(
        registration_enabled=settings_service.get(db, "registration.enabled", "true") != "false"
    )


@router.put("/settings/registration", response_model=RegistrationSetting)
async def set_registration(
    data: RegistrationSetting,
    admin: User = Depends(require_admin),
    db: Session = Depends(get_db),
):
    """Open or close self-registration (takes effect immediately)."""
    settings_service.set_value(
        db, "registration.enabled", "true" if data.registration_enabled else "false"
    )
    audit_service.record(
        db,
        admin,
        audit_service.SETTING_REGISTRATION,
        detail="open" if data.registration_enabled else "closed",
    )
    return data


